#!/usr/bin/env bash
# Craft Studio Setup bootstrapper (macOS).
#
# One line, pinned to a release tag:
#   curl -fsSL https://raw.githubusercontent.com/qualixar/craft-studio-setup/v0.3.0/install.sh | bash -s -- all
#   ... | bash -s -- adobe          (creator apps: PhotoCraft, VectorCraft, FilmCraft, ...)
#   ... | bash -s -- microsoft      (office apps: WordCraft, GridCraft, DeckCraft, ...)
#   ... | bash -s -- all --dry-run  (show every file and config it would touch; change nothing)
#   ... | bash -s -- uninstall      (remove what this installer added)
#
# Every other option is passed to scripts/install.sh (see --help), for example
#   --only gridcraft, --desktop, --claude-code, --claude-desktop, --both, --yes.
#
# What this file does:
#   1. downloads the tagged source tarball over HTTPS from github.com;
#   2. checks the SHA-256 of every script and catalog file it will use against
#      the list embedded below (this file itself is fetched from the same tag);
#   3. shows the plan (a dry run) and asks once before changing anything,
#      unless you passed --yes;
#   4. runs scripts/install.sh (or scripts/uninstall.sh) from the checked copy,
#      then deletes the temporary download.
# Run from a git clone (bash install.sh all) it uses the files next to it instead.
set -euo pipefail

CRAFT_SETUP_REF="v0.3.0"
CRAFT_SETUP_REPO="qualixar/craft-studio-setup"

# BEGIN CHECKSUMS (generated by scripts/update_checksums.py; do not edit by hand)
CRAFT_SETUP_SUMS='
44cdf779dc65f9a341736e0b8382d3715ff4034fa1328fc2709ef1592ab9b1a2  catalog/apps.json
749bf249e865293dac57e321741d9abfe818658050a88204bda99ab62fb02a6f  catalog/groups.json
1bdc30ce6b26ea1d1c3695aba7dbe06ab532882e41a191097d65e973214d3338  scripts/install.sh
b4602ab0c04245281bdf768052d416ba6a807a331a9d091072860b4f50075e15  scripts/mcp_config.py
e8ff4436e7ccf7a6ff4222ea4fd79bf552029eade01b0d48b86074afc3d6d000  scripts/uninstall.sh
8e9d4fcfe1e2c513898e7805d16cad6f65408248e8e8e4fff9a3e7953fb681d6  scripts/verify_mcp.py
'
# END CHECKSUMS

main() {
  local action="install" dry_run=0 yes=0 arg
  if [ "${1:-}" = "uninstall" ]; then action="uninstall"; shift; fi
  for arg in "$@"; do
    case "$arg" in
      --dry-run) dry_run=1;;
      --yes|-y) yes=1;;
      -h|--help) sed -n '2,23p' "${BASH_SOURCE[0]:-/dev/null}" 2>/dev/null | sed 's/^# \{0,1\}//' || true
                 echo "Full option list: scripts/install.sh --help"; return 0;;
    esac
  done

  if [ "$(uname -s)" != "Darwin" ]; then
    echo "Craft Studio Setup supports macOS only (Apple silicon and Intel). Windows and Linux are not supported." >&2
    return 1
  fi
  local tool
  for tool in curl tar shasum python3; do
    command -v "$tool" >/dev/null 2>&1 || {
      echo "Missing $tool. Install Apple's command line tools first: xcode-select --install" >&2; return 1; }
  done

  local src="" self="${BASH_SOURCE[0]:-}" tmp=""
  if [ -n "$self" ] && [ -f "$self" ] && [ -f "$(dirname "$self")/scripts/install.sh" ] && [ -z "${CRAFT_SETUP_TARBALL:-}" ]; then
    src="$(cd "$(dirname "$self")" && pwd)"
    echo "Using the local checkout at $src (nothing downloaded)."
  else
    tmp="$(mktemp -d "${TMPDIR:-/tmp}/craft-setup.XXXXXX")"
    # shellcheck disable=SC2064 # expand now: tmp is local to main.
    trap "rm -rf '$tmp'" EXIT
    local tarball="$tmp/source.tar.gz"
    if [ -n "${CRAFT_SETUP_TARBALL:-}" ]; then
      cp "$CRAFT_SETUP_TARBALL" "$tarball"
      echo "Using local tarball $CRAFT_SETUP_TARBALL"
    else
      local url="https://codeload.github.com/$CRAFT_SETUP_REPO/tar.gz/refs/tags/$CRAFT_SETUP_REF"
      echo "Downloading Craft Studio Setup $CRAFT_SETUP_REF from github.com/$CRAFT_SETUP_REPO"
      curl -fsSL --proto '=https' --proto-redir '=https' --tlsv1.2 --retry 3 -o "$tarball" "$url" || {
        echo "Download failed. Check your connection and try again." >&2; return 1; }
    fi
    if [ -n "${CRAFT_SETUP_TARBALL_SHA256:-}" ]; then
      local got
      got="$(shasum -a 256 "$tarball" | awk '{print $1}')"
      [ "$got" = "$CRAFT_SETUP_TARBALL_SHA256" ] || {
        echo "CHECKSUM MISMATCH for the source tarball (expected $CRAFT_SETUP_TARBALL_SHA256, got $got). Nothing was installed." >&2
        return 1; }
      echo "Tarball checksum OK."
    fi
    mkdir "$tmp/src"
    tar -xzf "$tarball" -C "$tmp/src"
    local top
    top="$(find "$tmp/src" -mindepth 1 -maxdepth 1 -type d | head -1)"
    [ -n "$top" ] || { echo "The download did not contain the expected folder." >&2; return 1; }
    # Copy each listed file into a clean folder, check it there, and run only
    # from that folder: nothing else from the download can be executed or imported.
    src="$tmp/verified"
    local sha path actual checked=0
    while read -r sha path; do
      [ -n "$sha" ] || continue
      if [ -L "$top/$path" ] || [ ! -f "$top/$path" ]; then
        echo "CHECKSUM CHECK FAILED: $path is missing from the download or is not a plain file. Nothing was installed." >&2; return 1
      fi
      mkdir -p "$src/$(dirname "$path")"
      cp "$top/$path" "$src/$path"
      actual="$(shasum -a 256 "$src/$path" | awk '{print $1}')"
      if [ "$actual" != "$sha" ]; then
        echo "CHECKSUM MISMATCH for $path (expected $sha, got $actual). Nothing was installed." >&2; return 1
      fi
      checked=$((checked + 1))
    done <<< "$CRAFT_SETUP_SUMS"
    rm -rf "$tmp/src"
    echo "Verified $checked files against the checksums in this script ($CRAFT_SETUP_REF)."
  fi

  local script="$src/scripts/install.sh"
  [ "$action" = "uninstall" ] && script="$src/scripts/uninstall.sh"

  if [ "$dry_run" = 1 ] || [ "$yes" = 1 ]; then
    bash "$script" "$@" </dev/null
    return $?
  fi

  local plan
  plan="$(bash "$script" "$@" --dry-run </dev/null)" || { printf '%s\n' "$plan"; return 1; }
  printf '%s\n' "$plan"
  case "$plan" in
    *"Already installed, nothing changed."*|*"Nothing to do."*) return 0;;
  esac
  echo
  local answer=""
  if [ -t 0 ]; then
    printf 'Go ahead with the changes listed above? [y/N] '
    IFS= read -r answer || true
  elif { : </dev/tty; } 2>/dev/null; then
    printf 'Go ahead with the changes listed above? [y/N] ' >/dev/tty
    IFS= read -r answer </dev/tty || true
  else
    echo "No terminal is available to ask for your OK. Re-run with --yes to accept the plan above." >&2
    return 1
  fi
  case "$answer" in
    [Yy]*) bash "$script" "$@" --yes </dev/null;;
    *) echo "Nothing was changed."; return 1;;
  esac
}

# Everything runs from main, called on the last line, so a partial download of
# this file through a pipe can never execute half a script.
main "$@"
